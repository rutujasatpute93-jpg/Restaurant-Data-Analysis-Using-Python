import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os

print("All libraries imported successfully!")

df = pd.read_excel("/content/swiggy.csv.xlsx", sheet_name="zomato")

print("Dataset loaded successfully!")
print("Shape:", df.shape)

df.head()

df.columns

df.info()

df.isnull().sum()

df.describe()

df.columns = df.columns.str.strip()

print("Duplicate rows:", df.duplicated().sum())

df = df.drop_duplicates()

df["Cuisines"] = df["Cuisines"].fillna("Unknown")

print("Cleaned dataset shape:", df.shape)

ratings = df["Aggregate rating"].to_numpy()
costs = df["Average Cost for two"].to_numpy()

print("Average rating:", np.mean(ratings))
print("Highest rating:", np.max(ratings))
print("Lowest rating:", np.min(ratings))
print("Average cost for two:", np.mean(costs))
print("Restaurants rated 4 or above:", np.sum(ratings >= 4))

city_counts = df["City"].value_counts().head(10)

plt.figure(figsize=(10, 6))
sns.barplot(x=city_counts.values, y=city_counts.index)
plt.title("Top 10 Cities by Restaurant Count")
plt.xlabel("Number of Restaurants")
plt.ylabel("City")
plt.show()

plt.figure(figsize=(9, 5))
sns.histplot(df["Aggregate rating"], bins=20, kde=True)
plt.title("Restaurant Rating Distribution")
plt.show()

plt.figure(figsize=(9, 5))
sns.histplot(df["Average Cost for two"], bins=30, kde=True)
plt.title("Average Cost for Two People")
plt.show()

plt.figure(figsize=(9, 5))
sns.scatterplot(
    data=df,
    x="Votes",
    y="Aggregate rating",
    alpha=0.6
)
plt.title("Restaurant Ratings vs Votes")
plt.show()

delivery = df["Has Online delivery"].value_counts()

plt.figure(figsize=(7, 5))
plt.pie(
    delivery.values,
    labels=delivery.index,
    autopct="%1.1f%%"
)
plt.title("Online Delivery Availability")
plt.show()

df.to_csv("cleaned_restaurant_data.csv", index=False)